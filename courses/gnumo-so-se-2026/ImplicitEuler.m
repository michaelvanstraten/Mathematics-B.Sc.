function appx = ImplicitEuler(t0, tf, M, y0, f, Df, tol)
  stepSize = (tf - t0) / M;
  appx = [y0];
  u = y0;
  t = t0;
  for k = 2:(M+1)
    t = t + stepSize;
    u = NewtonMethod( ...
      @(x) u - stepSize * f(t, x) - x, ...
      @(x) - stepSize * Df(t, x) - 1, ...
      u, ...
      tot ...
    );
    appx(k) = u;
  end
end
